type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, values?: TranslationValues) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

export function LocaleProvider({
  children,
  initialLocale,
}: {
  children: React.ReactNode;
  initialLocale: Locale;
}) {
  const [locale, setCurrentLocale] = useState(initialLocale);
  const setLocale = useCallback((nextLocale: Locale) => {
    setCurrentLocale(nextLocale);
    document.documentElement.lang = nextLocale;
    document.cookie = `study_locale=${nextLocale}; path=/; max-age=31536000; samesite=lax`;
  }, []);
  const t = useCallback(
    (key: string, values: TranslationValues = {}) => {
      let output = locale === "en" ? key : (translations[locale][key] ?? key);
      for (const [name, value] of Object.entries(values)) {
        output = output.replaceAll(`{${name}}`, String(value));
      }
      return output;
    },
    [locale],
  );
  const context = useMemo(
    () => ({ locale, setLocale, t }),
    [locale, setLocale, t],
  );

  return (
    <LocaleContext.Provider value={context}>{children}</LocaleContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("useI18n must be used within LocaleProvider.");
  return context;
}
